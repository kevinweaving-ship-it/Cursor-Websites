#!/usr/bin/env python3
"""Build nginx geo + allow files from Google's published crawler CIDRs.

Sources (official, not user-triggered fetchers):
  https://developers.google.com/static/search/apis/ipranges/googlebot.json
  https://developers.google.com/static/search/apis/ipranges/special-crawlers.json

Do not include user-triggered-fetchers*.json — those are Google users, not Googlebot.
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

SOURCES = (
    "https://developers.google.com/static/search/apis/ipranges/googlebot.json",
    "https://developers.google.com/static/search/apis/ipranges/special-crawlers.json",
)

HERE = Path(__file__).resolve().parent
GEO_OUT = HERE / "nginx-googlebot-cidrs.inc"
ALLOW_OUT = HERE / "nginx-sailingsa-googlebot-allow.conf"


def _load(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "SailingSA-googlebot-cidrs/1"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def collect(local_files: list[Path] | None = None) -> tuple[list[str], list[str]]:
    seen: set[str] = set()
    cidrs: list[str] = []
    created: list[str] = []
    payloads = []
    if local_files:
        for path in local_files:
            payloads.append(json.loads(path.read_text(encoding="utf-8")))
    else:
        for url in SOURCES:
            payloads.append(_load(url))
    for data in payloads:
        created.append(str(data.get("creationTime") or ""))
        for item in data.get("prefixes") or []:
            cidr = item.get("ipv4Prefix") or item.get("ipv6Prefix")
            if not cidr or cidr in seen:
                continue
            seen.add(cidr)
            cidrs.append(cidr)
    return cidrs, created


def write_files(cidrs: list[str], created: list[str]) -> None:
    header = (
        "# Official Googlebot + special-crawlers CIDRs.\n"
        "# Generated by googlebot_cidrs_build.py — do not hand-edit.\n"
        "# source_times: %s\n" % (", ".join(x for x in created if x) or "unknown")
    )
    geo_lines = [header, "# nginx geo include: address value;\n"]
    allow_lines = [
        "# Official Google crawler allow-list. Include BEFORE sailingsa-swarm-deny.conf\n",
        "# so allow wins if a deny ever overlaps. First-match allow/deny.\n",
        header,
    ]
    for cidr in cidrs:
        geo_lines.append("%s 1;\n" % cidr)
        allow_lines.append("allow %s;\n" % cidr)
    GEO_OUT.write_text("".join(geo_lines), encoding="utf-8")
    ALLOW_OUT.write_text("".join(allow_lines), encoding="utf-8")
    print("wrote %s (%d cidrs)" % (GEO_OUT, len(cidrs)))
    print("wrote %s" % ALLOW_OUT)


def main() -> int:
    local = [Path(p) for p in sys.argv[1:]] if len(sys.argv) > 1 else None
    cidrs, created = collect(local)
    if not cidrs:
        print("no CIDRs collected", file=sys.stderr)
        return 1
    write_files(cidrs, created)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
